#!/usr/bin/env python
"""Генератор батчей 870-891 — по 50 KnowledgeUnits (1100 фактов)."""
from __future__ import annotations

import os

OUT = "docs/knowledge/world_skills_core/ru"


def mk(ns: str, items: list[tuple]) -> list[tuple]:
    return [(f"{ns}.{s}", t, typ, e, p) for s, t, typ, e, p in items]


def write_batch(num: int, fname: str, title: str, ns: str, scope: str, facts: list[tuple]) -> None:
    assert len(facts) == 50, f"BATCH {num}: expected 50 facts, got {len(facts)}"
    path = os.path.join(OUT, fname)
    lines = [
        f"# BATCH {num}: {title}",
        "",
        f"**KnowledgeUnits:** {len(facts)}",
        f"**Namespace:** `{ns}.*`",
        f"**Scope:** {scope}",
        "",
        "| ID | KnowledgeUnit | Тип | Суть | Практический смысл |",
        "|---|---|---|---|---|",
    ]
    for fid, t, typ, e, p in facts:
        lines.append(f"| {fid} | {t} | {typ} | {e} | {p} |")
    lines.append("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {fname}: {len(facts)} facts")


