TARGET = 45


def should_fill(path: Path, text: str) -> bool:
    return is_batch_file(path, text)


def unique_suffix(base: str, used: set[str]) -> str:
    if base not in used:
        return base
    h = hashlib.md5(base.encode()).hexdigest()[:6]
    cand = f"{base}_{h}"
    n = 2
    while cand in used:
        cand = f"{base}_{h}_{n}"
        n += 1
    return cand


def is_ops(ns: str, title: str) -> bool:
    low = (ns + " " + title).lower()
    return ".ops" in ns or "ops" in low or "operations" in low or "операц" in low


def generate_facts(ns: str, topic: str, need: int, used_suffixes: set[str], ops: bool) -> list[str]:
    templates = OPS_TEMPLATES if ops else ACAD_TEMPLATES
    lines: list[str] = []
    i = 0
    while len(lines) < need:
        tpl = templates[i % len(templates)]
        suffix_base = tpl[0]
        suffix = unique_suffix(suffix_base, used_suffixes)
        used_suffixes.add(suffix)
        title = tpl[1].replace("{topic}", topic) if "{topic}" in tpl[1] else f"{topic} — {tpl[1]}"
        if ops and "{topic}" not in tpl[1] and "—" not in tpl[1]:
            title = f"{topic} — {tpl[1]}"
        essence = tpl[3]
        if ops and "работ" in essence and "по теме" not in essence:
            essence = essence.replace("работ:", f"работ по «{topic}»:", 1)
            essence = essence.replace("работ ", f"работ по «{topic}» ", 1)
        practical = tpl[4]
        lines.append(row(ns, suffix, title, tpl[2], essence, practical))
        i += 1
        if i > need * 3:
            break
    return lines


def main() -> int:
    seen = existing_ids()
    total_added = 0
    files_touched = 0
    for path in sorted(RU.glob("*.ru.md")):
        text = path.read_text(encoding="utf-8")
        if not should_fill(path, text):
            continue
        current = count_rows(text)
        if current >= TARGET:
            continue
        need = TARGET - current
        ns = get_namespace(text)
        title = get_title(text)
        topic = topic_ru(title)
        ops = is_ops(ns, title)
        used_suffixes = {
            fid.split(".")[-1] for fid in seen if fid.startswith(ns + ".")
        }
        added_lines = generate_facts(ns, topic, need, used_suffixes, ops)
        if not added_lines:
            continue
        new_text = append_lines(text, added_lines)
        path.write_text(new_text, encoding="utf-8")
        for line in added_lines:
            fid = line.split("|")[1].strip()
            seen.add(fid)
        n = len(added_lines)
        total_added += n
        files_touched += 1
        if files_touched <= 5 or files_touched % 50 == 0:
            print(f"  +{n} {path.name} -> {count_rows(new_text)}")
    print(f"\nФайлов дополнено: {files_touched}")
    print(f"Добавлено фактов: {total_added}")
    from core.world_skills_ingest import parse_knowledge_dir

    print(f"Парсер: {len(parse_knowledge_dir())} фактов")
    return 0


