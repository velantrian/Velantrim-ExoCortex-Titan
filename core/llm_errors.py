"""Safe LLM failure reporting.

A provider exception can carry request headers, a URL that contains a credential,
a masked or full API key echoed back by the provider, or part of the prompt. Nothing
built from ``str(exc)`` / ``repr(exc)`` / a traceback may be returned to a caller,
logged, persisted in a trace, or sent as an event.

Callers get a fixed code from this module plus a random event id. The exception text
is not stored anywhere, so the event id correlates a user report with a log line that
names the code, the exception *types* (with causes) and the code location that raised
(file, line, function: taken from the code, never from data).

Credentials with characters that cannot be sent in an HTTP header are rejected before
any request is built (``validate_llm_api_key``): the HTTP library would otherwise raise
an error whose text contains the whole header value.
"""

from __future__ import annotations

import re
import uuid
from dataclasses import dataclass
from typing import Any

# Visible ASCII only: no whitespace, no control characters (CR/LF/NUL), no non-ASCII.
_API_KEY_RE = re.compile(r"[\x21-\x7e]+")
# A policy reason code (for example ``network_denied``) is generated by this repository, not by a
# provider. It is passed through only when it has this strict shape.
_REASON_CODE_RE = re.compile(r"[a-z0-9_.-]{1,64}")
# The fields of an error report have a fixed shape, whatever built them.
_CODE_RE = re.compile(r"[a-z0-9_]{1,64}")
_EVENT_ID_RE = re.compile(r"llm_evt_[0-9a-f]{16}")


class LlmKeyInvalidError(ValueError):
    """The API key contains characters that are not allowed. The message is fixed."""

    def __init__(self) -> None:
        super().__init__("LLM API key contains characters that are not allowed")


class LlmNotConfiguredError(ValueError):
    """No usable LLM configuration or key. ``ValueError`` for backward compatibility."""


class LlmEmptyResponseError(ValueError):
    """The provider answered without usable content. ``ValueError`` for backward compatibility."""


def validate_llm_api_key(key: str | None) -> None:
    """Reject a key that cannot be placed in an HTTP header. An empty key is the
    caller's concern (not configured), not a format error."""
    if key and _API_KEY_RE.fullmatch(key) is None:
        raise LlmKeyInvalidError()


# code -> fixed hint shown to the user. Static text only; never derived from an exception.
_HINTS: dict[str, str] = {
    "llm_key_invalid": "ключ провайдера содержит недопустимые символы (пробелы, переводы строк, не-ASCII) — введите его заново",
    "llm_not_configured": "LLM не настроен: укажите провайдера и ключ",
    "llm_auth_failed": "неверный или просроченный API ключ",
    "llm_access_denied": "HTTP 403: доступ запрещён — проверьте, что API включён для ключа (Generative Language API для Gemini) и нет региональных ограничений",
    "llm_quota_exceeded": "недостаточно баланса на аккаунте",
    "llm_model_not_found": "модель не найдена — проверьте имя модели",
    "llm_rate_limited": "лимит запросов — повторите позже",
    "llm_timeout": "провайдер не ответил вовремя",
    "llm_unreachable": "не удалось подключиться к провайдеру",
    "llm_provider_unavailable": "провайдер временно недоступен",
    "llm_provider_rejected": "провайдер отклонил запрос",
    "llm_empty_response": "провайдер вернул пустой ответ — повторите запрос или смените модель",
    "llm_circuit_open": "LLM временно отключён после серии ошибок",
    "llm_egress_denied": "отправка данных внешнему провайдеру запрещена политикой",
    "llm_cancelled": "вызов отменён",
    "llm_request_invalid": "некорректный запрос к LLM",
    "llm_internal_error": "внутренняя ошибка при обращении к LLM",
}

# Codes that map to a specific HTTP status for the connectivity-test routes; every other
# code keeps the historical 400.
_HTTP_STATUS = {
    "llm_auth_failed": 401,
    "llm_quota_exceeded": 402,
    "llm_model_not_found": 404,
    "llm_rate_limited": 429,
}


def new_event_id() -> str:
    return "llm_evt_" + uuid.uuid4().hex[:16]


@dataclass(frozen=True)
class LlmErrorInfo:
    code: str
    event_id: str
    detail: str = ""  # policy reason code for egress denials, otherwise empty

    def __post_init__(self) -> None:
        # Structural guarantee: these fields are echoed to callers, logs and events, so a
        # value that does not have the fixed shape (for example text copied from a provider
        # by a future caller) is replaced, never passed through.
        if not (isinstance(self.code, str) and _CODE_RE.fullmatch(self.code)):
            object.__setattr__(self, "code", "llm_internal_error")
        if not (isinstance(self.event_id, str) and _EVENT_ID_RE.fullmatch(self.event_id)):
            object.__setattr__(self, "event_id", new_event_id())
        if not (isinstance(self.detail, str) and _REASON_CODE_RE.fullmatch(self.detail)):
            object.__setattr__(self, "detail", "")

    @property
    def hint(self) -> str:
        return _HINTS.get(self.code, _HINTS["llm_internal_error"])

    @property
    def http_status(self) -> int:
        return _HTTP_STATUS.get(self.code, 400)


def _code_for_status(status: int) -> str:
    if status == 401:
        return "llm_auth_failed"
    if status == 403:
        return "llm_access_denied"
    if status == 402:
        return "llm_quota_exceeded"
    if status == 404:
        return "llm_model_not_found"
    if status == 429:
        return "llm_rate_limited"
    if status == 408 or status >= 500:
        return "llm_provider_unavailable"
    return "llm_provider_rejected"


class LlmStreamError(Exception):
    """Carries an already-safe error event (code, event id) across a re-raise."""

    def __init__(self, info: LlmErrorInfo) -> None:
        super().__init__(info.code)
        self.info = info


def classify_llm_error(exc: BaseException) -> str:
    """Map an exception to a fixed code using its *type* (and a status code), never its text."""
    import httpx

    from core.circuit_breaker import CircuitBreakerOpenError
    from core.llm_router import (
        LlmCallCancelledError,
        LlmProviderRequestError,
    )
    from core.remote_egress import RemoteEgressDeniedError

    if isinstance(exc, LlmStreamError):
        return exc.info.code
    if isinstance(exc, LlmKeyInvalidError):
        return "llm_key_invalid"
    if isinstance(exc, LlmNotConfiguredError):
        return "llm_not_configured"
    if isinstance(exc, LlmEmptyResponseError):
        return "llm_empty_response"
    if isinstance(exc, LlmCallCancelledError):
        return "llm_cancelled"
    if isinstance(exc, CircuitBreakerOpenError):
        return "llm_circuit_open"
    if isinstance(exc, RemoteEgressDeniedError):
        return "llm_egress_denied"
    if isinstance(exc, LlmProviderRequestError):
        return _code_for_status(int(exc.status_code))
    if isinstance(exc, (TimeoutError, httpx.TimeoutException)):
        return "llm_timeout"
    if isinstance(exc, (httpx.TransportError, OSError)):
        return "llm_unreachable"
    if isinstance(exc, ValueError):
        return "llm_request_invalid"
    return "llm_internal_error"


def _policy_reason(exc: BaseException) -> str:
    from core.remote_egress import RemoteEgressDeniedError

    if isinstance(exc, RemoteEgressDeniedError):
        reason = getattr(exc, "reason_code", "")
        if isinstance(reason, str) and _REASON_CODE_RE.fullmatch(reason):
            return reason
    return ""


def describe_llm_failure(exc: BaseException) -> LlmErrorInfo:
    if isinstance(exc, LlmStreamError):
        return exc.info
    return LlmErrorInfo(
        code=classify_llm_error(exc),
        event_id=new_event_id(),
        detail=_policy_reason(exc),
    )


def safe_llm_error_text(info: LlmErrorInfo) -> str:
    code = f"{info.code} ({info.detail})" if info.detail else info.code
    return f"[LLM error: {code} — {info.hint} (event {info.event_id})]"


def safe_llm_error_meta(info: LlmErrorInfo) -> dict[str, Any]:
    # "error" is kept for existing clients; it now holds the code, never exception text.
    meta: dict[str, Any] = {"error": info.code, "error_code": info.code, "event_id": info.event_id}
    if info.detail:
        meta["detail_code"] = info.detail
    return meta


_ORIGIN_TOKEN_RE = re.compile(r"[^A-Za-z0-9_.<>-]")


def _exception_types(exc: BaseException, *, limit: int = 4) -> str:
    """Type names of the exception and its causes (``A<-B<-C``). Names only, no messages."""
    names: list[str] = []
    seen: set[int] = set()
    current: BaseException | None = exc
    while current is not None and id(current) not in seen and len(names) < limit:
        seen.add(id(current))
        names.append(_ORIGIN_TOKEN_RE.sub("_", type(current).__name__)[:64])
        current = current.__cause__ or current.__context__
    return "<-".join(names)


def _exception_origin(exc: BaseException) -> str:
    """Where the exception was raised: ``file.py:line:function`` of the innermost frame.

    These come from the code, not from data: no argument values, no local variables, no
    message. They let an operator find the failing line although the text is not stored.
    """
    tb = exc.__traceback__
    if tb is None:
        return "unknown"
    while tb.tb_next is not None:
        tb = tb.tb_next
    code = tb.tb_frame.f_code
    filename = code.co_filename.replace("\\", "/").rsplit("/", 1)[-1]
    return ":".join(
        (
            _ORIGIN_TOKEN_RE.sub("_", filename)[:64],
            str(tb.tb_lineno),
            _ORIGIN_TOKEN_RE.sub("_", code.co_name)[:64],
        )
    )


def log_llm_failure(
    logger: Any, info: LlmErrorInfo, exc: BaseException, *, route: str, level: str = "warning"
) -> None:
    """One log line: route, code, event id, the exception *types* (with causes) and the code
    location that raised. No message, no traceback (``exc_info`` would print the message)."""
    getattr(logger, level)(
        "LLM call failed route=%s code=%s event_id=%s exc_type=%s origin=%s",
        route,
        info.code,
        info.event_id,
        _exception_types(exc),
        _exception_origin(exc),
    )


